@app.post("/process/supervised")
async def process_supervised(
    file: UploadFile = File(...),
    target_col: str = Form(...),
    test_size: float = Form(0.20),
    random_state: int = Form(42)
):

    df = await read_csv_upload(file)

    if target_col not in df.columns:

        raise HTTPException(
            status_code=400,
            detail=(
                f"Target column '{target_col}' "
                "was not found in the dataset."
            )
        )

    try:

        result = process_supervised_dataset(
            df=df,
            target_col=target_col,
            test_size=test_size,
            random_state=random_state
        )

    except Exception as e:

        raise HTTPException(
            status_code=500,
            detail=(
                "Supervised preprocessing failed: "
                f"{e}"
            )
        )

    X_train = result["X_train"]
    X_test = result["X_test"]

    return {
        "status": "success",
        "mode": "supervised",
        "task": result["task"],
        "target": target_col,

        "train_rows": int(
            X_train.shape[0]
        ),

        "test_rows": int(
            X_test.shape[0]
        ),

        "train_columns": int(
            X_train.shape[1]
        ),

        "test_columns": int(
            X_test.shape[1]
        ),

        "pipeline_info": result["info"]
    }


