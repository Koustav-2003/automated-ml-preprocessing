def dataframe_csv_response(
    df,
    filename
):

    csv_bytes = df.to_csv(
        index=False
    ).encode("utf-8")

    return StreamingResponse(
        io.BytesIO(csv_bytes),
        media_type="text/csv",
        headers={
            "Content-Disposition":
                f'attachment; filename="{filename}"'
        }
    )


