# ==========================================================
# CSV READER
# ==========================================================

async def read_csv_upload(
    file: UploadFile
):

    if not file.filename:

        raise HTTPException(
            status_code=400,
            detail="No file name supplied."
        )

    suffix = Path(
        file.filename
    ).suffix.lower()

    if suffix != ".csv":

        raise HTTPException(
            status_code=400,
            detail="Only CSV files are supported."
        )

    try:

        contents = await file.read()

        if not contents:

            raise HTTPException(
                status_code=400,
                detail="Uploaded file is empty."
            )

        df = pd.read_csv(
            io.BytesIO(contents)
        )

    except HTTPException:
        raise

    except Exception as e:

        raise HTTPException(
            status_code=400,
            detail=f"Could not read CSV: {e}"
        )

    if df.empty:

        raise HTTPException(
            status_code=400,
            detail="The uploaded dataset contains no rows."
        )

    return df


# ==========================================================
# DATASET INFORMATION
# ==========================================================

@app.post("/dataset/info")
async def dataset_info(
    file: UploadFile = File(...)
):

    df = await read_csv_upload(file)

    numerical = df.select_dtypes(
        include="number"
    ).columns.tolist()

    categorical = df.select_dtypes(
        exclude="number"
    ).columns.tolist()

    missing = (
        df.isna()
        .sum()
    )

    missing_features = (
        missing[
            missing > 0
        ]
        .sort_values(
            ascending=False
        )
        .to_dict()
    )

    return {
        "filename": file.filename,
        "rows": int(df.shape[0]),
        "columns": int(df.shape[1]),
        "features": df.columns.tolist(),
        "numerical_features": numerical,
        "categorical_features": categorical,
        "missing_features": {
            str(k): int(v)
            for k, v in missing_features.items()
        },
        "duplicate_rows": int(
            df.duplicated().sum()
        )
    }


